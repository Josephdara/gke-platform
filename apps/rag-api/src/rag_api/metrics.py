"""Prometheus metrics with bounded label values. Request IDs stay in logs."""

from prometheus_client import Counter, Gauge, Histogram, disable_created_metrics
from starlette.types import Scope

METHODS = frozenset({"GET", "HEAD", "POST", "PUT", "PATCH", "DELETE", "OPTIONS"})
# Generation on CPU takes tens of seconds, so the buckets reach the 120-second deadline.
SLOW_BUCKETS = (0.5, 1, 2, 5, 10, 15, 20, 30, 45, 60, 90, 120, 180)

disable_created_metrics()
REQUESTS = Counter("http_requests", "HTTP requests handled, excluding health probes.", ["method", "route", "status"])
DURATION = Histogram("http_request_duration_seconds", "HTTP request duration, excluding health probes.", ["method", "route"])

RAG_REQUESTS = Counter("rag_requests", "Chat requests by final outcome.", ["status"])
RAG_TTFT = Histogram("rag_ttft_seconds", "Time from request to the first token.", buckets=SLOW_BUCKETS)
RAG_COMPLETION = Histogram("rag_completion_seconds", "Time from request to the terminal event.", buckets=SLOW_BUCKETS)
RAG_RETRIEVAL = Histogram("rag_retrieval_seconds", "Time spent retrieving passages.")
RAG_GENERATED_TOKENS = Counter("rag_generated_tokens", "Tokens generated by the model.")
RAG_ACTIVE_STREAMS = Gauge("rag_active_streams", "Chat streams in progress on this replica.")
RAG_REJECTIONS = Counter("rag_rejections", "Chat requests refused before generation.", ["reason"])
RAG_INVALID_CITATIONS = Counter("rag_invalid_citations", "Citations in answers that name no retrieved passage.")

# Every value the status label can take, so dashboards see a stable set.
OUTCOMES = ("complete", "length", "cancelled", "deadline", "stalled", "upstream_failed", "model_unavailable")
REJECTION_REASONS = ("admission", "rate_limit", "input_too_long")
for outcome in OUTCOMES:
    RAG_REQUESTS.labels(outcome)
for reason in REJECTION_REASONS:
    RAG_REJECTIONS.labels(reason)


def record_request(scope: Scope, status: int, seconds: float) -> None:
    method = scope["method"] if scope["method"] in METHODS else "other"
    route = getattr(scope.get("route"), "path", "unmatched")
    REQUESTS.labels(method, route, str(status)).inc()
    DURATION.labels(method, route).observe(seconds)
